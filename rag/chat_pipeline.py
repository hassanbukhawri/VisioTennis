"""
Chat turn orchestration -- wires rag/chat_router.py's classifier + backstops
together with the 3 prompt paths into one entry point,
handle_chat_turn(), for the backend chat endpoint to call.

See rag/chat_router.py's module docstring and PROJECT_LOG.md's chat
grounding architecture entry for the full design. Summary of the 3 tiers
this dispatches to:

  tier 1 (route="existing_citation"): template-stitch, NO generation --
    replays the matched stored item verbatim.
  tier 2 (route="new_grounded_claim"): rag/stroke_prompt.py's
    build_stroke_chat_prompt() through the unchanged retry-gate
    (rag/gated_pipeline.py:generate_grounded_response).
  tier 3 (route="general_note" / "unavailable_comparison"): a single-shot,
    citation-free generation, checked by
    chat_router.check_tier3_response_for_smuggled_claims() before being
    trusted -- escalates to tier 2 if that check fails, exactly the
    misclassification safety net verified in
    rag/run_chat_router_trials.py Part B.2/B.3.

Every successful tier-2 generation (whether reached directly via
"new_grounded_claim" or via a tier-3 escalation) additionally passes through
chat_router.check_for_skill_tier_mismatch() before being trusted (backstop
#3, see chat_router.py's module docstring) -- a real, mechanically-grounded
percentile citation answering a skill-tier-framed question ("at my level")
is downgraded to the "unavailable_comparison" disclaimer instead of shown,
regardless of what classify_turn() originally decided.

A 5th route, "progress_digest" (2026-08-12, see PROJECT_LOG.md's cross-
session digest entry), asks about trend/progress ACROSS sessions rather than
this one stroke. Dispatches to _run_progress_digest_checked() -- same
retry-gate machinery as tier 2, same skill-tier-mismatch backstop (extended
to also cover SessionDigest citations, not just biomechanics_percentile.
ones -- see check_for_skill_tier_mismatch()'s docstring for why both carry
the same flat-population risk), sourced from a freshly-computed
ir/schema.py:SessionDigest instead of a StrokeEvent. If no digest is
available yet (a new player, or every session so far failed pose detection),
a fixed, code-authored message is shown -- never an LLM attempt to describe
a trend that doesn't exist.
"""
import json
from dataclasses import dataclass, field

from rag.chat_router import (
    ExistingCitation, check_for_skill_tier_mismatch, check_tier3_response_for_smuggled_claims, classify_turn,
)
from rag.gated_pipeline import generate_grounded_response
from rag.prompt import build_schema_instructions, build_tone_instruction
from rag.run_qwen_eval import clean_json_text
from rag.schema import ChatRouteDecision, CoachingFeedbackItem, CoachingResponse
from rag.stroke_prompt import build_stroke_chat_prompt

# Fixed, code-authored -- never generated by the LLM, same "don't trust the
# model to remember to write this" philosophy as UNAVAILABLE_COMPARISON_DISCLAIMER
# below. Shown when classify_turn() picks "progress_digest" but no real digest
# exists yet (ir/session_digest.py:compute_session_digest returned None) --
# never let a generation attempt invent a trend from nothing.
NO_DIGEST_AVAILABLE_MESSAGE = (
    "You don't have enough recorded sessions yet for a progress trend -- come back after a few more "
    "practice sessions and I'll be able to show you how things are moving."
)

DIGEST_SCHEMA_INSTRUCTIONS = build_schema_instructions(
    record_type="SessionDigest",
    record_display_name="SESSION_DIGEST",
    id_field_name="record_id",
    feature_scope_rule=(
        'Only cite fields that are actually present in {RECORD}: "trailing_averages.<feature>" for a '
        'feature listed there, "trend_deltas.<feature>" for a feature listed there (if "trend_deltas" is '
        'empty, there is NO trend data available -- you may describe the player\'s current standing from '
        '"trailing_averages" but must NOT claim any upward/downward movement, improvement, or decline), '
        '"stroke_type_mode", or "session_count". Do not invent a feature name not listed in '
        '"trailing_averages"/"trend_deltas".'
    ),
    include_percentile_rule=False,
    item_count_rule=(
        'Produce 1 to 3 items that directly answer the player\'s question about their progress/trend -- '
        'do not repeat feedback already given earlier in this conversation.'
    ),
)

# Fixed, code-authored -- never generated by the LLM (see rag/chat_router.py's
# module docstring: the whole point is not trusting the model to remember to
# write this itself). Shown verbatim before whatever general guidance the
# tier-3 generation produced.
UNAVAILABLE_COMPARISON_DISCLAIMER = (
    "I don't have benchmark data to compare you against -- here's general guidance:"
)

TIER3_SYSTEM_PROMPT = (
    "You are a tennis coaching assistant. Answer the player's question with general, non-personalized "
    "tennis advice or knowledge only -- you have NOT been given this player's own measurements on this "
    "turn, so you must NOT reference, estimate, or invent any specific number, percentage, percentile, "
    "or comparison about this particular player. Respond with ONLY a single JSON object (no markdown "
    "fences, no prose before or after) matching exactly this shape:\n\n"
    '{ "items": [ { "text": "<your answer>", "type": "general_note" } ] }\n\n'
    "Hard rules:\n"
    '1. EVERY item MUST include BOTH keys, "text" AND "type" -- "type" must always be the literal string '
    '"general_note" on every single item, with no exceptions, even the last one. Never omit "type". Never '
    'include a "citation" key.\n'
    "2. Do not state any specific number, percentage, or comparison ('better than', 'above average', "
    "'higher than X') anywhere in \"text\" -- if you don't have real data to back a specific claim, keep "
    "the advice general.\n"
    "3. Produce 1 to 2 items."
)

# Tier 3 is meant to be the CHEAP lane -- no grounding retry-gate applies here (there's nothing to
# re-check against real data on this tier). But qwen3:8b has a documented tendency to drop a required
# field on a trailing JSON item (the exact "field omitted on a trailing item" failure noted in
# rag/gated_pipeline.py's own module docstring, confirmed again here in
# rag/run_chat_pipeline_trials.py -- both real tier-3 test messages hit it on the first attempt). That's
# a pure JSON-formatting slip, not a hallucination/smuggled-claim risk, so it gets a small, cheap retry
# budget of its own (regenerate from scratch) BEFORE falling through to a full tier-2 escalation --
# escalating a formatting slip to the expensive gate would defeat tier 3's entire cost purpose.
TIER3_MAX_PARSE_ATTEMPTS = 2


def _format_chat_history(conversation_history: list[tuple[str, str]]) -> str:
    if not conversation_history:
        return "(no earlier turns in this conversation)"
    return "\n".join(f"{role}: {text}" for role, text in conversation_history)


def build_tier3_prompt(
    conversation_history: list[tuple[str, str]], user_message: str, tone_profile: dict | None = None,
) -> tuple[str, str]:
    """tone_profile: see rag/stroke_prompt.py:build_stroke_prompt()'s docstring
    -- same optional, additive-only convention (None -> TIER3_SYSTEM_PROMPT
    unchanged, byte-identical to before this feature existed)."""
    tone_instruction = build_tone_instruction(tone_profile)
    system_prompt = f"{TIER3_SYSTEM_PROMPT}\n\n{tone_instruction}" if tone_instruction else TIER3_SYSTEM_PROMPT
    user_prompt = (
        f"CONVERSATION SO FAR:\n{_format_chat_history(conversation_history)}\n\n"
        f'PLAYER\'S QUESTION: "{user_message}"\n\n'
        f"Answer now."
    )
    return system_prompt, user_prompt


def build_progress_digest_prompt(
    digest, conversation_history: list[tuple[str, str]], user_message: str, tone_profile: dict | None = None,
) -> tuple[str, str]:
    """route="progress_digest" chat prompt -- the cross-session analog of
    build_stroke_chat_prompt(), citing a freshly-computed
    ir/schema.py:SessionDigest (see ir/session_digest.py) instead of a
    StrokeEvent. digest: a SessionDigest.model_dump(mode="json") dict.

    No KB retrieval here (unlike build_stroke_prompt/build_prompt) --
    no progress/trend-framing knowledge-base content exists, and building
    one is out of scope for this feature; the model works from the digest's
    own numbers plus the schema instructions' plain-language framing rule
    (rule 6, reused via DIGEST_SCHEMA_INSTRUCTIONS) instead.

    tone_profile: see build_stroke_prompt()'s docstring -- same optional,
    additive-only convention."""
    tone_instruction = build_tone_instruction(tone_profile)
    tone_block = f"\n\n{tone_instruction}" if tone_instruction else ""

    system_prompt = (
        "You are a tennis coaching assistant answering a player's question about their progress/trend "
        "ACROSS RECENT SESSIONS. You must base every factual or trend claim STRICTLY on the "
        "SESSION_DIGEST JSON given to you in the user message -- never on general tennis knowledge, "
        "never on numbers you compute yourself. Every number in this digest is a PERCENTILE RANK "
        "(0-100), already averaged/compared for you -- do not reinterpret it as a raw measurement. "
        "If \"trend_deltas\" is empty, there is NO trend data yet (not enough session history) -- you "
        "must say so honestly rather than invent an improving or declining trend; you may still "
        "describe the player's current standing from \"trailing_averages\" alone. This output will be "
        "checked automatically against the real SESSION_DIGEST data; any claim that doesn't trace back "
        "exactly will be flagged as ungrounded."
        + tone_block + "\n\n"
        + DIGEST_SCHEMA_INSTRUCTIONS
    )

    trailing_block = "\n".join(
        f"- {feat} = {val}th percentile (average over the last {digest['session_count']} session(s))"
        for feat, val in digest["trailing_averages"].items()
    )
    if digest["trend_deltas"]:
        thin_prior = digest["trend_prior_window_size"] < digest["lookback_k"]
        thin_note = (
            f" -- based on only {digest['trend_prior_window_size']} prior session(s) (fewer than the usual "
            f"{digest['lookback_k']}); mention in your answer that this trend is based on a small comparison "
            f"and could shift as more sessions come in" if thin_prior else ""
        )
        trend_block = "\n".join(
            f"- {feat}: {val:+.1f} percentile points vs. the prior {digest['trend_prior_window_size']} "
            f"session(s){thin_note}"
            for feat, val in digest["trend_deltas"].items()
        )
    else:
        trend_block = (
            f"(NO TREND DATA -- only {digest['total_sessions_considered']} usable session(s) exist so far, "
            f"fewer than the {digest['lookback_k'] * 2} needed for a recent-vs-prior comparison. Do not "
            f"claim any trend; you may only describe current standing from TRAILING_AVERAGES above.)"
        )

    user_prompt = (
        f"SESSION_DIGEST:\n{json.dumps(digest, indent=2)}\n\n"
        f"TRAILING_AVERAGES (current standing, average percentile rank per feature over the last "
        f"{digest['session_count']} session(s)):\n{trailing_block}\n\n"
        f"TREND_DELTAS (recent vs. prior window, percentile-POINT change -- positive means this "
        f"session's typical value ranks higher in our population than before, not necessarily "
        f"\"better,\" the same non-judgmental framing already used for single-session percentile "
        f"coaching):\n{trend_block}\n\n"
        f"Most-practiced stroke recently: {digest['stroke_type_mode'] or '(unknown)'}\n\n"
        f"CONVERSATION SO FAR:\n{_format_chat_history(conversation_history)}\n\n"
        f'PLAYER\'S QUESTION: "{user_message}"\n\n'
        f"Generate the JSON reply now."
    )
    return system_prompt, user_prompt


@dataclass
class ChatTurnResult:
    route: str  # the EFFECTIVE route actually served (may differ from the classifier's
    # initial decision if a tier-3 response was escalated -- see escalated_from_tier3)
    tier: int  # 1, 2, or 3 -- which cost tier actually executed
    text: str  # final player-facing text, disclaimer already prepended if applicable
    items: list = field(default_factory=list)  # list[CoachingFeedbackItem], for citation display
    success: bool = True
    failure_reason: str = ""
    n_attempts: int = 0
    total_latency_s: float = 0.0
    escalated_from_tier3: bool = False


def _find_existing_item(existing_items: list[CoachingFeedbackItem], field_path: str):
    for item in existing_items:
        if item.citation is not None and item.citation.ir_field_path == field_path:
            return item
    return None


def _run_tier2(backend, stroke_event, benchmark, conversation_history, user_message,
               embedder=None, max_attempts=3, escalated_from_tier3=False, tone_profile=None) -> ChatTurnResult:
    system_prompt, user_prompt = build_stroke_chat_prompt(
        stroke_event, benchmark, conversation_history, user_message, embedder=embedder, tone_profile=tone_profile)
    source_records = {("StrokeEvent", stroke_event["event_id"]): stroke_event}
    gated = generate_grounded_response(
        backend, system_prompt, user_prompt, source_records,
        max_attempts=max_attempts, percentile_benchmark=benchmark)
    if gated.success:
        return ChatTurnResult(
            route="new_grounded_claim", tier=2,
            text=" ".join(it.text for it in gated.response.items),
            items=list(gated.response.items), success=True,
            n_attempts=gated.n_attempts, total_latency_s=gated.total_latency_s,
            escalated_from_tier3=escalated_from_tier3,
        )
    return ChatTurnResult(
        route="new_grounded_claim", tier=2,
        text="I couldn't come up with a confidently-grounded answer to that one -- try rephrasing, "
             "or ask about a specific measurement from your results.",
        success=False, failure_reason=gated.failure_reason,
        n_attempts=gated.n_attempts, total_latency_s=gated.total_latency_s,
        escalated_from_tier3=escalated_from_tier3,
    )


def _run_progress_digest(backend, digest: dict, conversation_history, user_message,
                          max_attempts=3, tone_profile=None) -> ChatTurnResult:
    """route="progress_digest" -- the cross-session analog of _run_tier2(),
    through the SAME unchanged retry-gate (generate_grounded_response),
    sourced from a SessionDigest record instead of a StrokeEvent.
    percentile_benchmark is not passed: SessionDigest citations are plain
    dotted-path lookups (see rag/schema.py:Citation's SessionDigest
    docstring), never the "biomechanics_percentile." recompute path, so
    there's nothing for that parameter to do here."""
    system_prompt, user_prompt = build_progress_digest_prompt(
        digest, conversation_history, user_message, tone_profile=tone_profile)
    source_records = {("SessionDigest", digest["record_id"]): digest}
    gated = generate_grounded_response(
        backend, system_prompt, user_prompt, source_records, max_attempts=max_attempts)
    if gated.success:
        return ChatTurnResult(
            route="progress_digest", tier=2,
            text=" ".join(it.text for it in gated.response.items),
            items=list(gated.response.items), success=True,
            n_attempts=gated.n_attempts, total_latency_s=gated.total_latency_s,
        )
    return ChatTurnResult(
        route="progress_digest", tier=2,
        text="I couldn't come up with a confidently-grounded answer about your progress -- try "
             "rephrasing, or ask about a specific measurement instead.",
        success=False, failure_reason=gated.failure_reason,
        n_attempts=gated.n_attempts, total_latency_s=gated.total_latency_s,
    )


def _run_progress_digest_checked(backend, digest: dict, conversation_history, user_message,
                                  max_attempts=3, tone_profile=None) -> ChatTurnResult:
    """_run_progress_digest() plus the SAME skill-tier-mismatch backstop
    tier 2 gets (rag/chat_router.py:check_for_skill_tier_mismatch, extended
    to also cover SessionDigest citations -- trailing_averages/trend_deltas
    are themselves computed from the same flat, non-skill-stratified
    percentile population as a direct biomechanics_percentile. citation, see
    ir/session_digest.py, so a message combining trend language with
    skill-tier framing ("has my progress been good for my level?") carries
    the identical mislabeling risk backstop #3 already exists for."""
    result = _run_progress_digest(backend, digest, conversation_history, user_message,
                                   max_attempts=max_attempts, tone_profile=tone_profile)
    if not result.success or check_for_skill_tier_mismatch(user_message, result.items):
        return result

    response3, safe3, latency3 = _generate_tier3_response(backend, conversation_history, user_message, tone_profile)
    total_latency = result.total_latency_s + latency3
    if response3 is not None and safe3:
        fallback = _finish_tier3_result(response3, "unavailable_comparison", total_latency)
        return fallback
    return ChatTurnResult(
        route="unavailable_comparison", tier=3, success=False,
        text="I don't have benchmark data to compare you against, and couldn't generate general "
             "guidance either -- try rephrasing your question.",
        total_latency_s=total_latency,
    )


def _generate_tier3_response(backend, conversation_history, user_message, tone_profile=None):
    """Runs tier 3's single-shot, citation-free generation with its small
    parse-retry budget (TIER3_MAX_PARSE_ATTEMPTS) and smuggled-claims safety
    check (check_tier3_response_for_smuggled_claims). Returns (response,
    safe, latency_s) -- response is None if every attempt failed to parse
    (safe is then also False). Factored out so both the normal tier-3
    dispatch and the skill-tier-mismatch fallback below (backstop #3) run
    the identical generation+check, not two copies of it."""
    system_prompt, user_prompt = build_tier3_prompt(conversation_history, user_message, tone_profile=tone_profile)
    response = None
    safe = False
    total_latency = 0.0
    for _ in range(TIER3_MAX_PARSE_ATTEMPTS):
        result = backend.generate(system_prompt, user_prompt)
        total_latency += result.latency_s
        try:
            cleaned = clean_json_text(result.raw_text)
            response = CoachingResponse.model_validate(json.loads(cleaned))
        except Exception:
            continue  # pure parse failure -- cheap retry, not an escalation-worthy event
        safe = check_tier3_response_for_smuggled_claims(response)
        break  # parsed successfully; whether it's safe or not is now decided, don't keep retrying
    return response, safe, total_latency


def _finish_tier3_result(response, route, latency_s, n_attempts=1) -> ChatTurnResult:
    text = " ".join(it.text for it in response.items)
    if route == "unavailable_comparison":
        text = f"{UNAVAILABLE_COMPARISON_DISCLAIMER} {text}"
    return ChatTurnResult(
        route=route, tier=3, text=text, items=list(response.items),
        success=True, n_attempts=n_attempts, total_latency_s=latency_s,
    )


def _run_tier2_checked(backend, stroke_event, benchmark, conversation_history, user_message,
                        embedder=None, max_attempts=3, escalated_from_tier3=False, tone_profile=None) -> ChatTurnResult:
    """_run_tier2() plus the skill-tier-mismatch backstop (rag/chat_router.py
    :check_for_skill_tier_mismatch, module docstring backstop #3): a
    successful, fully-grounded tier-2 result can still answer a
    skill-tier-framed question ("at my level") with a flat-population
    percentile citation it has no business supporting for that framing --
    see PROJECT_LOG.md's 2026-08-12 entry for the real observed case this
    catches. When that happens, the tier-2 result is discarded and replaced
    with a fresh "unavailable_comparison" tier-3 response (the same
    disclaimer-prefixed shape a correctly-classified turn would have
    gotten), never silently returned as-is."""
    result = _run_tier2(backend, stroke_event, benchmark, conversation_history, user_message,
                         embedder=embedder, max_attempts=max_attempts,
                         escalated_from_tier3=escalated_from_tier3, tone_profile=tone_profile)
    if not result.success or check_for_skill_tier_mismatch(user_message, result.items):
        return result

    response3, safe3, latency3 = _generate_tier3_response(backend, conversation_history, user_message, tone_profile)
    total_latency = result.total_latency_s + latency3
    if response3 is not None and safe3:
        fallback = _finish_tier3_result(response3, "unavailable_comparison", total_latency)
        fallback.escalated_from_tier3 = escalated_from_tier3
        return fallback
    # Even the safe disclaimer path failed to produce a parseable/safe
    # response -- showing the skill-tier-mismatched tier-2 result would be
    # worse than an honest failure, so fail explicitly rather than fall back
    # to it.
    return ChatTurnResult(
        route="unavailable_comparison", tier=3, success=False,
        text="I don't have benchmark data to compare you against, and couldn't generate general "
             "guidance either -- try rephrasing your question.",
        total_latency_s=total_latency, escalated_from_tier3=escalated_from_tier3,
    )


def handle_chat_turn(
    backend, stroke_event: dict, benchmark,
    existing_items: list[CoachingFeedbackItem], existing_citations: list[ExistingCitation],
    conversation_history: list[tuple[str, str]], user_message: str,
    embedder=None, max_attempts=3, tone_profile: dict | None = None, digest: dict | None = None,
) -> ChatTurnResult:
    """Single entry point for one chat turn -- classify, then dispatch to
    whichever tier the (mechanically-backstopped) decision calls for.

    tone_profile: see rag/stroke_prompt.py:build_stroke_prompt()'s docstring
    -- threaded through to whichever tier actually generates text (tier 1
    never generates, so it's unaffected by definition).

    digest: an ir/schema.py:SessionDigest.model_dump(mode="json") dict, or
    None if ir/session_digest.py:compute_session_digest() found no usable
    session history for this player yet -- see the "progress_digest" branch
    below for how None is handled (a fixed message, never a generation
    attempt). Callers not wired up for the digest feature can simply omit
    this (defaults to None), same additive-only convention as tone_profile."""
    decision = classify_turn(backend, existing_citations, conversation_history, user_message)

    if decision.route == "existing_citation":
        item = _find_existing_item(existing_items, decision.matched_field_path)
        if item is not None:
            return ChatTurnResult(route="existing_citation", tier=1, text=item.text, items=[item], success=True)
        # classify_turn()'s own backstop already verifies matched_field_path against
        # existing_citations, so this should be unreachable -- but never trust a
        # lookup blindly just because an earlier check passed; fall through to the
        # safe default rather than assume.
        decision = ChatRouteDecision(route="new_grounded_claim", matched_field_path=None)

    if decision.route == "new_grounded_claim":
        return _run_tier2_checked(backend, stroke_event, benchmark, conversation_history, user_message,
                                   embedder=embedder, max_attempts=max_attempts, tone_profile=tone_profile)

    if decision.route == "progress_digest":
        if digest is None:
            # No real digest exists for this player yet -- a fixed,
            # code-authored message, never an LLM attempt to describe a
            # trend from nothing (same philosophy as UNAVAILABLE_COMPARISON_
            # DISCLAIMER: don't trust the model to remember to say "I don't
            # have this," say it in code).
            return ChatTurnResult(route="progress_digest", tier=3, text=NO_DIGEST_AVAILABLE_MESSAGE, success=True)
        return _run_progress_digest_checked(backend, digest, conversation_history, user_message,
                                             max_attempts=max_attempts, tone_profile=tone_profile)

    # tier 3: "general_note" or "unavailable_comparison"
    response, safe, total_tier3_latency = _generate_tier3_response(
        backend, conversation_history, user_message, tone_profile)

    if not safe:
        # Misclassification safety net (rag/run_chat_router_trials.py Part B.2/B.3):
        # either the tier-3 generation didn't parse, or it smuggled in a claim it
        # had no legitimate way to ground -- escalate to the full retry-gate
        # instead of showing an unverified response.
        return _run_tier2_checked(backend, stroke_event, benchmark, conversation_history, user_message,
                                   embedder=embedder, max_attempts=max_attempts, escalated_from_tier3=True,
                                   tone_profile=tone_profile)

    return _finish_tier3_result(response, decision.route, total_tier3_latency)
